logger = logging.getLogger(__name__)


class TestGeneratorError(Exception):
    """Base exception for test-case generation failures."""


class AnalysisInputError(TestGeneratorError):
    """The analysis JSON or its findings are missing or invalid."""


class ContractSourceError(TestGeneratorError):
    """A required Solidity contract source could not be found or read."""


class ModelGenerationError(TestGeneratorError):
    """The local model could not generate a usable Solidity test."""


def _project_path(path: str | Path) -> Path:
    """Resolve a path and ensure it stays inside this project."""
    candidate = Path(path)
    if not candidate.is_absolute():
        candidate = PROJECT_ROOT / candidate
    resolved = candidate.resolve()
    try:
        resolved.relative_to(PROJECT_ROOT)
    except ValueError as exc:
        raise ValueError("Path must stay inside the project directory.") from exc
    return resolved


def load_analysis(analysis_path: str | Path | None = None) -> tuple[dict[str, Any], Path]:
    """Load analysis generated by report_reader.py, with support for the notebook's old file."""
    selected = analysis_path
    if selected is None:
        selected = DEFAULT_ANALYSIS_PATH

    try:
        path = _project_path(selected)
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise AnalysisInputError(
            f"Analysis JSON not found: {selected}. Run report_reader.py first."
        ) from exc
    except PermissionError as exc:
        raise AnalysisInputError(f"Permission denied reading analysis JSON: {selected}") from exc
    except UnicodeDecodeError as exc:
        raise AnalysisInputError(f"Analysis JSON is not UTF-8: {selected}") from exc
    except json.JSONDecodeError as exc:
        raise AnalysisInputError(
            f"Invalid analysis JSON at line {exc.lineno}, column {exc.colno}."
        ) from exc
    except (OSError, ValueError) as exc:
        raise AnalysisInputError(f"Could not read analysis JSON: {selected}") from exc

    if not isinstance(data, dict):
        raise AnalysisInputError("Analysis JSON must contain a JSON object.")
    return data, path


def _analysis_results(data: dict[str, Any]) -> list[dict[str, Any]]:
    # Accept the correctly spelled key and the typo used by the notebook.
    results = data.get("analysis_results")
    if results is None:
        results = data.get("analysis_resuls", [])
    if not isinstance(results, list):
        raise AnalysisInputError("'analysis_results' must be a list.")
    normalized = [item for item in results if isinstance(item, dict)]
    if not normalized:
        raise AnalysisInputError("The analysis JSON contains no usable findings.")
    return normalized


def _as_name_list(value: Any) -> list[str]:
    """Normalize a field that may be a string, list of strings, or null."""
    if value is None:
        return []
    values = value if isinstance(value, list) else [value]
    return [str(item).strip() for item in values if item and str(item).strip()]


def build_vulnerability_parameters(
    analysis_data: dict[str, Any],
) -> list[dict[str, Any]]:
    """Get vulnerability, contract, and function parameters from each finding."""
    vul_params: list[dict[str, Any]] = []
    try:
        for index, result in enumerate(_analysis_results(analysis_data), start=1):
            vul_params.append({
                "finding_id": str(result.get("id") or f"finding_{index:02d}"),
                "vul": result.get("vulnerability_type"),
                "contracts": _as_name_list(result.get("affected_contracts")),
                "functions": _as_name_list(result.get("affected_functions")),
                "title": result.get("title"),
                "root_cause": result.get("root_cause"),
                "impact": result.get("impact"),
                "recommendation": result.get("recommendation"),
            })
    except (TypeError, AttributeError) as exc:
        raise AnalysisInputError("Finding data has an invalid structure.") from exc
    return vul_params


def extract_function_code(source_code: str, function_name: str) -> str:
    # Regex para encontrar onde a função começa
    pattern = rf"(function\s+{re.escape(function_name)}\s*\([^)]*\)[^{{]*\{{)"
    match = re.search(pattern, source_code)

    if not match:
        return f"// Function '{function_name}' was not found in the source."

    start_idx = match.start()
    open_brace_idx = match.end() - 1

    # Contagem de chaves para capturar até o fechamento correto '}'
    brace_count = 1
    current_idx = open_brace_idx + 1

    while current_idx < len(source_code) and brace_count > 0:
        char = source_code[current_idx]
        if char == "{":
            brace_count += 1
        elif char == "}":
            brace_count -= 1
        current_idx += 1

    if brace_count != 0:
        raise ContractSourceError(f"Function '{function_name}' has unbalanced braces.")
    return source_code[start_idx:current_idx]


def _contract_directory(analysis_data: dict[str, Any]) -> Path:
    """Use the directory recorded by analysis when available; otherwise use this project's data path."""
    configured_path = analysis_data.get("contracts_dir")
    if configured_path:
        try:
            candidate = _project_path(configured_path)
            if candidate.is_dir():
                return candidate
        except ValueError as exc:
            raise ContractSourceError("The contracts_dir in the analysis leaves the project.") from exc

    if CONTRACTS_DIR.is_dir():
        return CONTRACTS_DIR
    raise ContractSourceError(f"Contract directory not found: {CONTRACTS_DIR}")


def load_contract_sources(
    vul_params: list[dict[str, Any]],
    contracts_dir: str | Path,
) -> dict[str, dict[str, str]]:
    """Read only contracts referenced by findings."""
    contract_dir = _project_path(contracts_dir)
    if not contract_dir.is_dir():
        raise ContractSourceError(f"Contract directory not found: {contract_dir}")

    # Get the source code from the affected contracts
    names: set[str] = set()
    for params in vul_params:
        names.update(Path(name).stem for name in params["contracts"])
        for function in params["functions"]:
            if "." in function:
                names.add(function.split(".", 1)[0].removesuffix(".sol"))

    contract_code: dict[str, dict[str, str]] = {}
    try:
        for path in contract_dir.rglob("*.sol"):
            if path.stem not in names:
                continue
            contract_code[path.stem] = {
                "c_name": path.stem,
                "source_code": path.read_text(encoding="utf-8"),
                "path": str(path.relative_to(PROJECT_ROOT)),
            }
    except (OSError, UnicodeDecodeError) as exc:
        raise ContractSourceError(f"Could not read Solidity files under {contract_dir}.") from exc

    missing_names = names - contract_code.keys()
    if missing_names:
        logger.warning("Contract source not found for: %s", ", ".join(sorted(missing_names)))
    return contract_code


def build_generation_parameters(
    vul_params: list[dict[str, Any]],
    contract_code: dict[str, dict[str, str]],
) -> list[dict[str, Any]]:
    """Create one model request per affected contract, using target function snippets."""
    params: list[dict[str, Any]] = []
    for finding in vul_params:
        # Mapeia as funções por contrato: {'NomeDoContrato': ['fn1', 'fn2']}
        contract_target_fns: dict[str, list[str]] = {}
        for function in finding["functions"]:
            if "." in function:
                c_name, f_name = function.split(".", 1)
                f_name = f_name.split("(", 1)[0].strip().removesuffix(".sol")
                contract_target_fns.setdefault(Path(c_name).stem, []).append(f_name)

        target_contracts = set(Path(name).stem for name in finding["contracts"])
        target_contracts.update(contract_target_fns)
        for contract_name in sorted(target_contracts):
            contract = contract_code.get(contract_name)
            if not contract:
                continue

            fn_list = contract_target_fns.get(contract_name, [])
            if fn_list:
                extracted_snippets = []
                for fn_name in dict.fromkeys(fn_list):
                    snippet = extract_function_code(contract["source_code"], fn_name)
                    if not snippet.startswith("// Function '"):
                        extracted_snippets.append(snippet)
                # Use the full source if the report's function name does not match Solidity.
                trimmed_source = "\n\n".join(extracted_snippets) or contract["source_code"]
            else:
                trimmed_source = contract["source_code"]

            params.append({
                "finding_id": finding["finding_id"],
                "vulnerability": finding["vul"] or "Unspecified vulnerability",
                "title": finding.get("title"),
                "root_cause": finding.get("root_cause"),
                "impact": finding.get("impact"),
                "recommendation": finding.get("recommendation"),
                "target_functions": fn_list,
                "contract_name": contract_name,
                "contract_path": contract["path"],
                "source_code": trimmed_source,
            })
    if not params:
        raise AnalysisInputError(
            "No test-generation parameters were produced. Check affected_contracts, "
            "affected_functions, and contracts_dir in the analysis JSON."
        )
    return params


def build_test_message(vulnerability_data: dict[str, Any]) -> list[dict[str, str]]:
    """Build one canonical Qwen prompt for a single vulnerability/contract pair."""
    target_functions = vulnerability_data.get("target_functions", [])
    functions_text = ", ".join(target_functions) if target_functions else "(not specified)"
    user_prompt = USER_PROMPT_TEMPLATE.format(
        finding_id=vulnerability_data["finding_id"],
        vulnerability=vulnerability_data["vulnerability"],
        contract_name=vulnerability_data["contract_name"],
        target_functions=functions_text,
        source_code=vulnerability_data["source_code"],
    )
    # Include report context when the analysis contains it.
    context = []
    for key, label in (
        ("title", "Title"),
        ("root_cause", "Root cause"),
        ("impact", "Impact"),
        ("recommendation", "Recommendation"),
    ):
        value = vulnerability_data.get(key)
        if value:
            context.append(f"- {label}: {value}")
    if context:
        user_prompt = user_prompt.replace(
            "Target functions:",
            "Report context:\n" + "\n".join(context) + "\n\nTarget functions:",
        )
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_prompt},
    ]


def _parse_model_response(content: str) -> dict[str, str]:
    """Parse JSON output and retain notebook-compatible code-fence fallback."""
    if not isinstance(content, str) or not content.strip():
        raise ModelGenerationError("The local model returned an empty response.")
    try:
        result = json.loads(content, strict=False)
    except json.JSONDecodeError:
        result = None

    if isinstance(result, dict):
        return result

    # Fallback: accept a Solidity code block if the model ignored the JSON instruction.
    block_match = re.search(r"```(?:solidity)?\s*(.*?)\s*```", content, re.DOTALL | re.IGNORECASE)
    if block_match:
        return {
            "test_file_name": "ItyFuzzTest.sol",
            "solidity_test_code": block_match.group(1).strip(),
        }

    # Notebook fallback: recover the JSON string value for solidity_test_code.
    key_match = re.search(r'"solidity_test_code"\s*:\s*', content)
    if key_match:
        decoder = json.JSONDecoder()
        value_start = content.find('"', key_match.end())
        if value_start >= 0:
            try:
                code, _ = decoder.raw_decode(content[value_start:])
                return {"test_file_name": "ItyFuzzTest.sol", "solidity_test_code": code}
            except json.JSONDecodeError:
                pass

    raise ModelGenerationError("The model response was not valid JSON and had no Solidity code block.")


def call_llm_agent_api(messages: list[dict[str, str]]) -> dict[str, str]:
    """Call the local Ollama OpenAI-compatible endpoint with the selected Qwen model."""
    if not messages:
        raise ValueError("messages cannot be empty.")
    try:
        client = OpenAI(
            base_url=OLLAMA_BASE_URL,
            api_key="ollama",
            timeout=240.0,
            max_retries=1,
        )
        completion = client.chat.completions.create(
            model=MODEL_NAME,
            messages=messages,
            temperature=0,
            top_p=1,
            response_format={"type": "json_object"},
            extra_body={
                "num_ctx": 8192,
                "num_predict": 4096,
            },
        )
        content = completion.choices[0].message.content
        return _parse_model_response(content or "")
    except openai.APIConnectionError as exc:
        raise ModelGenerationError(
            "Ollama is unavailable at http://localhost:11434/v1. Start it in WSL "
            "with 'ollama serve' and confirm the model is installed with 'ollama list'."
        ) from exc
    except openai.APIStatusError as exc:
        raise ModelGenerationError(
            f"Ollama returned HTTP {exc.status_code}. Confirm that {MODEL_NAME!r} "
            "is installed and supports the requested response format."
        ) from exc
    except openai.APIError as exc:
        raise ModelGenerationError("Ollama returned an API error.") from exc


def _safe_file_name(value: Any) -> str:
    """Keep model-generated filenames inside the test-case artifact directory."""
    name = Path(str(value or "ItyFuzzTest.sol")).name
    if not name.lower().endswith(".sol"):
        name += ".sol"
    name = re.sub(r"[^A-Za-z0-9_.-]", "_", name)
    if name in {"", ".", ".."}:
        return "ItyFuzzTest.sol"
    return name


def save_test_case(
    vulnerability_data: dict[str, Any],
    response: dict[str, Any],
) -> Path:
    """Save each generated test in its own directory under outputs/test_cases."""
    code = response.get("solidity_test_code")
    if not isinstance(code, str) or not code.strip():
        raise ModelGenerationError("The model response has no 'solidity_test_code'.")

    finding_slug = re.sub(r"[^A-Za-z0-9_.-]", "_", vulnerability_data["finding_id"])
    contract_slug = re.sub(r"[^A-Za-z0-9_.-]", "_", vulnerability_data["contract_name"])
    case_dir = _project_path(TEST_CASES_DIR / f"{finding_slug}_{contract_slug}")
    case_dir.mkdir(parents=True, exist_ok=True)
    output_path = _project_path(case_dir / _safe_file_name(response.get("test_file_name")))
    try:
        output_path.write_text(code.strip() + "\n", encoding="utf-8")
    except (OSError, UnicodeEncodeError) as exc:
        raise TestGeneratorError(f"Could not save generated test to {output_path}.") from exc
    return output_path


def generate_test_cases(
    analysis_path: str | Path | None = None,
) -> dict[str, Any]:
    """Run the notebook flow for every finding and save a generation summary in outputs/."""
    analysis_data, used_analysis_path = load_analysis(analysis_path)
    vulnerability_params = build_vulnerability_parameters(analysis_data)
    contracts_dir = _contract_directory(analysis_data)
    contract_code = load_contract_sources(vulnerability_params, contracts_dir)
    generation_params = build_generation_parameters(vulnerability_params, contract_code)

    generated: list[dict[str, Any]] = []
    failures: list[dict[str, str]] = []
    for item in generation_params:
        try:
            messages = build_test_message(item)
            response = call_llm_agent_api(messages)
            output_path = save_test_case(item, response)
            generated.append({
                "finding_id": item["finding_id"],
                "contract": item["contract_name"],
                "functions": item["target_functions"],
                "file": str(output_path.relative_to(PROJECT_ROOT)),
            })
            logger.info("Generated test case: %s", output_path)
        except (TestGeneratorError, openai.APIError, OSError, TypeError, ValueError) as exc:
            logger.exception(
                "Test generation failed for %s / %s",
                item["finding_id"],
                item["contract_name"],
            )
            failures.append({
                "finding_id": item["finding_id"],
                "contract": item["contract_name"],
                "error": str(exc),
            })

    summary = {
        "analysis_file": str(used_analysis_path.relative_to(PROJECT_ROOT)),
        "model": MODEL_NAME,
        "generated_count": len(generated),
        "failure_count": len(failures),
        "test_cases": generated,
        "failures": failures,
    }
    try:
        OUTPUTS_DIR.mkdir(parents=True, exist_ok=True)
        _project_path(GENERATION_SUMMARY_PATH).write_text(
            json.dumps(summary, indent=2, ensure_ascii=False),
            encoding="utf-8",
        )
    except (OSError, ValueError) as exc:
        raise TestGeneratorError(
            f"Could not save generation summary to {GENERATION_SUMMARY_PATH}."
        ) from exc

    if not generated and failures:
        raise ModelGenerationError(
            f"No test cases were generated. See {GENERATION_SUMMARY_PATH} for details."
        )
    return summary


def main() -> int:
    try:
        summary = generate_test_cases()
    except TestGeneratorError as exc:
        logger.error("Test generation stopped: %s", exc)
        return 1

    logger.info(
        "Finished: %s generated, %s failed. Summary: %s",
        summary["generated_count"],
        summary["failure_count"],
        GENERATION_SUMMARY_PATH,
    )
    return 0


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
    raise SystemExit(main())
